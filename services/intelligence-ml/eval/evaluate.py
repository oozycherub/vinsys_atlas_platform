"""Writes the attrition evaluation report and model card (`python eval/evaluate.py`).

The checked-in report is generated from the SYNTHETIC workforce in intelligence_ml.synthetic, so
it shows the method and the gates working, not the model's quality on real HR data: each tenant's
own metrics are stored with its model (attrition_models.metrics) and served to HRBPs by
`GET /v1/attrition/model`. tests/test_evaluate.py checks the files are current.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from intelligence_ml import synthetic
from intelligence_ml.attrition import features as feats
from intelligence_ml.attrition import model as mdl
from intelligence_ml.attrition.pipeline import matrix

DOCS = Path(__file__).resolve().parents[1] / 'docs'


def evaluate() -> dict[str, Any]:
    fs = synthetic.features(3000, 6, seed=7)
    X = matrix(fs.rows, feats.FEATURE_NAMES)
    keep, dropped = feats.select(
        feats.FEATURE_NAMES, feats.proxy_report(X, feats.FEATURE_NAMES, fs.audit)
    )
    m = mdl.train(
        X[:, [feats.FEATURE_NAMES.index(n) for n in keep]], fs.y, fs.order, keep, fs.audit
    )
    assert m is not None
    proxy = synthetic.features(1500, 3, seed=8, proxy=True)
    Xp = matrix(proxy.rows, feats.FEATURE_NAMES)
    _, proxy_dropped = feats.select(
        feats.FEATURE_NAMES, feats.proxy_report(Xp, feats.FEATURE_NAMES, proxy.audit)
    )
    importance = sorted(
        zip(keep, m.booster.feature_importance(importance_type='gain'), strict=True),
        key=lambda kv: -float(kv[1]),
    )
    return {
        'rows': len(fs.rows),
        'exit_rate': round(float(fs.y.mean()), 4),
        'metrics': m.metrics,
        'alerts_enabled': m.alerts_enabled,
        'features': keep,
        'dropped': dropped,
        'proxy_dropped': proxy_dropped,
        'importance': [(k, round(float(v), 1)) for k, v in importance],
    }


def _pct(v: float) -> str:
    return f'{v:.1%}'


def report(r: dict[str, Any]) -> str:
    m = r['metrics']
    parity = m['parity']['gender']
    lines = [
        '# Attrition model: evaluation report',
        '',
        '> **Synthetic data.** Generated by `eval/evaluate.py` from `intelligence_ml.synthetic`. These',
        '> numbers show the method and the gates working; they say nothing about real HR data. Each',
        "> tenant's own metrics are stored with its model and shown to HRBPs (`GET /v1/attrition/model`).",
        '',
        '## Data and split',
        '',
        f'- {r["rows"]:,} employee-month snapshots, voluntary-exit rate {_pct(r["exit_rate"])}.',
        f'- Time-based split: train {m["rows"]["train"]:,}, calibration {m["rows"]["calibration"]:,}, test {m["rows"]["test"]:,} (oldest to newest).',
        '',
        '## Results on the test slice',
        '',
        '| Metric | Value | Target (PRD §2.5(vi)) |',
        '| --- | --- | --- |',
        f'| AUC | {m["auc"]:.3f} | ≥ 0.75 |',
        f'| Precision at the top 10% | {m["precision_at_10"]:.3f} | ≥ 0.40 |',
        f'| Expected calibration error | {m["ece"]:.3f} | ≤ 0.10 (else alerts are disabled) |',
        f'| Flag-rate parity, gender (min/max) | {parity["ratio"]:.3f} | ≥ 0.80 (else alerts are disabled) |',
        '',
        f'Alerts enabled under these results: **{"yes" if r["alerts_enabled"] else "no"}**.',
        '',
        '## Feature governance',
        '',
        f'- Features used: {", ".join(f"`{f}`" for f in r["features"])}.',
        f'- Protected attributes refused as features: {", ".join(f"`{p}`" for p in sorted(feats.PROTECTED))}.',
        f'- Proxies dropped in this run (MI > {feats.MI_PROXY_LIMIT} bit): {"none" if not r["dropped"] else ", ".join(r["dropped"])}.',
        '- Proxy check on a dataset with a planted proxy: '
        + ', '.join(
            f'`{k}` dropped (MI {v["gender"]:.2f} bit with gender)'
            for k, v in r['proxy_dropped'].items()
        )
        + '.',
        '',
        '## Importance (gain)',
        '',
        '| Feature | Gain |',
        '| --- | --- |',
        *[f'| `{k}` | {v:,.1f} |' for k, v in r['importance']],
        '',
    ]
    return '\n'.join(lines)


CARD = """# Attrition model card

## Purpose

Flags employees whose risk of leaving voluntarily in the next 6 months has risen, so that an HR
business partner (HRBP) and the employee's manager can start a retention conversation. The alert
comes with the top 3 drivers in plain words, internal opportunities the employee is ready for
(readiness ≥ 0.6) and learning for their role gap.

## Not for

- Any decision about an employee: hiring, firing, pay, promotion or performance ratings.
- The employee's own view: employees never see risk scores (the API refuses them; ADR-0009).
- Anyone without the `hrbp` scope: managers learn of alerts through notifications only.

## Model

- LightGBM binary classifier with isotonic calibration (`intelligence_ml.attrition.model`).
- One model per tenant with at least 2,000 employees and 150 voluntary exits; otherwise a pooled
  model across tenants, trained on features that carry no tenant identity.
- Retrained monthly (Dagster `monthly_retrain`); scored nightly (`nightly`).
- Label: voluntary exit within 6 months of a snapshot. Involuntary exits are censored.
- Split: by time (train, calibration, test), never at random.

## Features

{features}

Protected attributes ({protected}) are never features. When a tenant supplies protected
attributes for audit, any feature with mutual information above {mi} bit against one of them is
dropped, and the dropped features are stored with the model.

## Gates (automatic)

- Expected calibration error above {ece}: alerts are switched off; analytics only.
- Four-fifths parity of flag rates across audit groups below {parity}: alerts are switched off.
- Population stability index above {psi} on any feature: recorded with the model and logged.

## Alerting rule

Probability at or above the tenant threshold (default 0.35) **and** a rise of at least 0.10 over 30
days or a first crossing; at most one alert per employee per 60 days.

## Explanations

SHAP (TreeExplainer) contributions towards leaving, top 3, mapped to phrases such as "No promotion
in 34 months".

## Oversight and data protection

- Attrition tables are readable only under the HRBP row-level-security policy, and every read is
  written to an append-only audit log.
- Erasure deletes an employee's scores, alerts, snapshots and audit attributes.
- The alert event carries drivers and actions, never the probability.

## Evaluation

See [evaluation_report.md](evaluation_report.md) (synthetic data) and each tenant's stored metrics.
"""


def card() -> str:
    example = {
        'tenure_months': 48,
        'months_since_promotion': 34,
        'months_in_role': 26,
        'compa_ratio': 0.87,
        'team_attrition_6m': 0.25,
        'peer_exits_6m': 3,
        'skill_gap': 0.3,
        'skill_gap_trend': 0.1,
        'internal_applications_6m': 2,
        'marketplace_rejections_6m': 1,
        'engagement_delta': -1.5,
        'overtime_hours_4w': 22,
    }
    listing = '\n'.join(
        f'- `{f.name}`, read as "{feats.phrase(f.name, example.get(f.name, 1.0))}"'
        for f in feats.FEATURES
    )
    values = {
        '{features}': listing,
        '{protected}': ', '.join(sorted(feats.PROTECTED)),
        '{mi}': str(feats.MI_PROXY_LIMIT),
        '{ece}': str(mdl.MAX_ECE),
        '{parity}': str(mdl.MIN_PARITY),
        '{psi}': str(mdl.PSI_ALERT),
    }
    out = CARD
    for k, v in values.items():
        out = out.replace(k, v)
    return out


def main() -> int:
    DOCS.mkdir(exist_ok=True)
    (DOCS / 'evaluation_report.md').write_text(report(evaluate()))
    (DOCS / 'model_card.md').write_text(card())
    sys.stdout.write(f'wrote {DOCS}/evaluation_report.md and model_card.md\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
