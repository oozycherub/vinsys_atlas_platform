// Generates the proctoring envelope test vectors (ADR-0007) with the platform's own JSON.stringify.
// Both the Go server (services/proctoring-svc) and the SDK (packages/proctor-sdk) must reproduce
// them byte for byte. Run: node packages/contracts/fixtures/generate-proctor-vectors.mjs
/* global Buffer, URL, console */
import { createHash, createHmac } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const canonical = (v) => {
  if (Array.isArray(v)) return '[' + v.map(canonical).join(',') + ']';
  if (v !== null && typeof v === 'object') {
    const keys = Object.keys(v).sort();
    return '{' + keys.map((k) => JSON.stringify(k) + ':' + canonical(v[k])).join(',') + '}';
  }
  return JSON.stringify(v);
};

const key = Buffer.from('6b65792d666f722d746573742d766563746f72732d3332627974657321212121', 'hex');
const session = '0192f0c1-0000-7000-8000-00000000abcd';
const events = [
  { type: 'heartbeat', client_ts: 1762336800123, payload: {} },
  { type: 'tab_hidden', client_ts: 1762336801234.5, payload: { duration_ms: 4200 } },
  {
    type: 'paste',
    client_ts: 1762336802000,
    payload: { chars: 512, target_question: 'q-1', sha256: 'ab'.repeat(32) },
  },
  {
    type: 'face_count',
    client_ts: 1762336803000,
    payload: {
      mp_faces: 2,
      score: 0.875,
      note: 'quote " backslash \\ tab \t newline \n bell \u0007',
    },
  },
  {
    type: 'frame',
    client_ts: 1762336804000,
    payload: {
      frame_id: '0192f0c1-0000-7000-8000-00000000f001',
      unicode: 'café ✓ 😀   end',
      nested: { z: [1, 2.5, -3e-7, 1e21], a: null, b: true },
    },
  },
  {
    type: 'keystroke_summary',
    client_ts: 1762336805000,
    payload: { é: 1, e: 2, Z: 3, '😀': 4, Ａ: 5 },
  },
];

let prev = '';
const vectors = events.map((e, i) => {
  const unsigned = {
    session_id: session,
    seq: i + 1,
    type: e.type,
    client_ts: e.client_ts,
    key_epoch: 1,
    payload: e.payload,
    prev_hash: prev,
  };
  const canonicalUnsigned = canonical(unsigned);
  const mac = createHmac('sha256', key).update(canonicalUnsigned).digest('hex');
  const signed = { ...unsigned, mac };
  const hash = createHash('sha256').update(canonical(signed)).digest('hex');
  prev = hash;
  return { wire: JSON.stringify(signed), canonical_unsigned: canonicalUnsigned, mac, hash };
});

const out = {
  comment: 'Generated by generate-proctor-vectors.mjs; see ADR-0007.',
  key_hex: key.toString('hex'),
  session_id: session,
  vectors,
};
writeFileSync(
  new URL('./proctor-envelope-vectors.json', import.meta.url),
  JSON.stringify(out, null, 2) + '\n',
);
console.log(vectors.length + ' vectors');
