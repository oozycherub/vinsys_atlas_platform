-- 0001_foundation: shared platform objects used by every service.
-- Applied by atlas_owner. Forward-only (ADR-0004).

-- Runtime role (created here as well so ephemeral databases, e.g. PGlite in tests, have it).
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'atlas_app') THEN
    CREATE ROLE atlas_app NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
  END IF;
END $$;

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO atlas_app;

-- Every table created by the owner from now on is usable by the app role; RLS still applies.
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atlas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO atlas_app;

-- Maintains updated_at on any table that has the column.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- Current tenant from the transaction-scoped setting; NULL when unset (fail closed in RLS).
CREATE OR REPLACE FUNCTION current_tenant_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid
$$;

-- Transactional outbox (MASTER_ORCHESTRATION_PROMPT §4.4). Debezium streams inserts to Kafka.
CREATE TABLE outbox_events (
  event_id        uuid PRIMARY KEY,                    -- UUIDv7 generated by the service
  tenant_id       uuid,                                -- NULL only for platform-wide events
  aggregate_type  text NOT NULL,
  aggregate_id    uuid NOT NULL,                       -- Kafka message key
  topic           text NOT NULL CHECK (topic ~ '^[a-z]+\.[a-z_]+\.[a-z_]+\.v[0-9]+$'),
  payload         jsonb NOT NULL,
  headers         jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_outbox_created ON outbox_events (created_at);

ALTER TABLE outbox_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE outbox_events FORCE ROW LEVEL SECURITY;
-- Services write their own tenant's events. Platform-wide events (tenant_id NULL) may only be
-- written inside a system transaction, which sets app.system = 'on'.
CREATE POLICY outbox_insert ON outbox_events FOR INSERT
  WITH CHECK (
    tenant_id = current_tenant_id()
    OR (tenant_id IS NULL AND current_setting('app.system', true) = 'on')
  );
CREATE POLICY outbox_select ON outbox_events FOR SELECT
  USING (
    tenant_id = current_tenant_id()
    OR current_setting('app.system', true) = 'on'
  );

-- Consumer-side de-duplication (at-least-once delivery → exactly-once effects).
CREATE TABLE processed_events (
  consumer    text NOT NULL,
  event_id    uuid NOT NULL,
  processed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (consumer, event_id)
);

-- Idempotency-Key storage for non-idempotent POSTs (MASTER_ORCHESTRATION_PROMPT §4.7).
CREATE TABLE idempotency_keys (
  scope           text NOT NULL,                       -- '<service>:<tenant_id|platform>:<principal>'
  idempotency_key text NOT NULL CHECK (length(idempotency_key) BETWEEN 8 AND 128),
  request_hash    text NOT NULL,                       -- sha256 of method + path + body
  response_status int,
  response_body   jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (scope, idempotency_key)
);
CREATE INDEX ix_idempotency_created ON idempotency_keys (created_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON outbox_events, processed_events, idempotency_keys TO atlas_app;
